// Deterministic noise shared by world generation and physics.

export function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const P = new Uint8Array(512);
{
  const r = mulberry32(1337);
  const p = Array.from({ length: 256 }, (_, i) => i);
  for (let i = 255; i > 0; i--) {
    const j = Math.floor(r() * (i + 1));
    const t = p[i]; p[i] = p[j]; p[j] = t;
  }
  for (let i = 0; i < 512; i++) P[i] = p[i & 255];
}
const GX = [1, -1, 1, -1, 1, -1, 0, 0];
const GY = [1, 1, -1, -1, 0, 0, 1, -1];

function grad(h, x, y) { h &= 7; return GX[h] * x + GY[h] * y; }
function fade(t) { return t * t * t * (t * (t * 6 - 15) + 10); }

// Perlin noise, roughly in [-1, 1].
export function noise2(x, y) {
  const xi = Math.floor(x), yi = Math.floor(y);
  const xf = x - xi, yf = y - yi;
  const X = xi & 255, Y = yi & 255;
  const aa = P[P[X] + Y], ab = P[P[X] + Y + 1], ba = P[P[X + 1] + Y], bb = P[P[X + 1] + Y + 1];
  const u = fade(xf), v = fade(yf);
  const g00 = grad(aa, xf, yf), g10 = grad(ba, xf - 1, yf);
  const g01 = grad(ab, xf, yf - 1), g11 = grad(bb, xf - 1, yf - 1);
  const x1 = g00 + u * (g10 - g00);
  const x2 = g01 + u * (g11 - g01);
  return x1 + v * (x2 - x1);
}

export function fbm2(x, y, oct = 4) {
  let s = 0, a = 0.5, f = 1, n = 0;
  for (let i = 0; i < oct; i++) {
    s += a * noise2(x * f + i * 17.3, y * f - i * 9.1);
    n += a; a *= 0.5; f *= 2.03;
  }
  return s / n;
}

